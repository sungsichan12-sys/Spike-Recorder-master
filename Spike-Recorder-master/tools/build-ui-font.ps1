# Reproducible, antialiased UI atlas. Logical cells remain 8 x 16 so existing
# scientific plots and control layouts retain their measurements.
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$bitmap = New-Object System.Drawing.Bitmap 512,1024
$graphics = [System.Drawing.Graphics]::FromImage($bitmap)
$graphics.Clear([System.Drawing.Color]::Black)
$graphics.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
$font = New-Object System.Drawing.Font 'Segoe UI',52,([System.Drawing.FontStyle]::Regular),([System.Drawing.GraphicsUnit]::Pixel)
$verticalScale = [Math]::Min(1.0,60.0 / $font.GetHeight($graphics))
$advances = @(0..127 | ForEach-Object { 32 })
$format = [System.Drawing.StringFormat]::GenericTypographic.Clone()
$format.FormatFlags = $format.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
# Keep the scientific symbols and line-drawing characters from the legacy font.
$legacy = [System.Drawing.Image]::FromFile((Join-Path $root 'data/ascii.bmp'))
$graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
$graphics.DrawImage($legacy,[System.Drawing.Rectangle]::new(0,512,512,512),0,128,128,128,[System.Drawing.GraphicsUnit]::Pixel)
for($code = 32; $code -lt 127; $code++) {
    $glyph = [string][char]$code
    $size = $graphics.MeasureString($glyph,$font,1000,$format)
    $scale = [Math]::Min(1.0,30.0 / [Math]::Max(1.0,$size.Width))
    $advances[$code] = [int][Math]::Ceiling($size.Width * $scale + 2)
    $saved = $graphics.Save()
    $cellX = ($code % 16)*32
    $cellY = [Math]::Floor($code/16)*64
    # Keep descenders and antialiasing inside their own cell, with a blank
    # gutter so scaled text cannot sample the preceding row of glyphs.
    $graphics.SetClip([System.Drawing.Rectangle]::new($cellX+1,$cellY+2,30,60))
    $graphics.TranslateTransform($cellX + (32-$size.Width*$scale)/2, $cellY + 2)
    $graphics.ScaleTransform($scale,$verticalScale)
    $graphics.DrawString($glyph,$font,[System.Drawing.Brushes]::White,0,0,$format)
    $graphics.Restore($saved)
}
$bitmap.Save((Join-Path $root 'data/ui-font.bmp'),[System.Drawing.Imaging.ImageFormat]::Bmp)
[IO.File]::WriteAllText((Join-Path $root 'src/widgets/UIFontMetrics.h'), "// Generated by tools/build-ui-font.ps1. Advance widths in quarter pixels.`nstatic const unsigned char uiFontAdvances[128] = {" + ($advances -join ',') + "};`n")
$legacy.Dispose(); $format.Dispose(); $font.Dispose(); $graphics.Dispose(); $bitmap.Dispose()
